"""Emit the N shard modules of the areal upper (C3) tiling (native_decide) from data/leaves_U4b.json: each shard
checks a contiguous block of leaves of ArealUCore/Leaves.lean between literal end points (joined by
`leavesOK_append`). Fork of tools/gen_arl_shards.py. usage: python3 -I gen_arlu_shards.py leaves.json NCHUNK OUTDIR"""
import json, sys
from fractions import Fraction as Fr
DEC = 10 ** 10
d = json.load(open(sys.argv[1])); n = int(sys.argv[2]); outdir = sys.argv[3]
L = [(Fr(l['Xp'], DEC << l['k']), l['Xp'], l['k']) for l in d['chord']] + [(Fr(w['Xu'], DEC << w['k']), w['Xu'], w['k']) for w in d['windows']]
L.sort(key=lambda t: t[0])
N = len(L); per = -(-N // n)
starts = list(range(0, N, per))
last = max([(Fr(l['Xq'], DEC << l['k']), l['Xq'], l['k']) for l in d['chord']] + [(Fr(w['Xv'], DEC << w['k']), w['Xv'], w['k']) for w in d['windows']])
names = []
for ci, a in enumerate(starts):
    b = min(a + per, N)
    X1, k1 = L[a][1], L[a][2]
    if b < N: X2, k2 = L[b][1], L[b][2]
    else: X2, k2 = last[1], last[2]
    name = f'Chunk{ci:03d}'
    names.append((name, a, b - a, X1, k1, X2, k2))
    open(f'{outdir}/{name}.lean', 'w').write(f'''import ArealUCore.Leaves

/-! Shard {ci} of the areal U4b tiling (N): leaves {a} .. {b - 1}. Generated by tools/gen_arlu_shards.py. -/

set_option maxRecDepth 200000
set_option maxHeartbeats 0

namespace ArealUCore.ArealUN

theorem chunk_{ci:03d} :
    leavesOK ctxU {X1} {k1} ((leaves.drop {a}).take {b - a}) {X2} {k2} = true := by
  native_decide

end ArealUCore.ArealUN
''')
print(len(names), 'chunks of', per, 'end', last[1:])
json.dump(names, open(f'{outdir}/chunks.json', 'w'))
