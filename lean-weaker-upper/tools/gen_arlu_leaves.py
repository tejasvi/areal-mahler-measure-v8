"""Emit ArealUCore/Leaves.lean (core Lean) and a text list for the native runner from the upper tiling output: the
leaves sorted by position, tiling [e_0, e_N]. Untrusted hints: the checker verifies everything.
usage: python3 -I gen_arlu_leaves.py leaves.json OUT.lean OUT.txt"""
import json, sys, hashlib
from fractions import Fraction as Fr
DEC = 10 ** 10
raw = open(sys.argv[1], 'rb').read(); sha = hashlib.sha256(raw).hexdigest()
d = json.loads(raw)
assert not d['fails']
L = [(Fr(l['Xp'], DEC << l['k']), 0, l['Xp'], l['Xq'], l['k'], bool(l['x0q']), l['mask']) for l in d['chord']]
L += [(Fr(w['Xu'], DEC << w['k']), 1, w['Xu'], w['Xv'], w['k'], False, 0) for w in d['windows']]
L.sort(key=lambda t: t[0])
for a, b in zip(L, L[1:]):
    assert Fr(a[3], DEC << a[4]) == Fr(b[2], DEC << b[4]), (a, b)
x0 = L[0][0]; xt = Fr(L[-1][3], DEC << L[-1][4])
assert x0 == Fr(29, 200) and xt == 20, (x0, xt)
out = ['import ArealUCore.Check', '',
       f'/-! Leaves of the areal U4b tiling of `[29/200, 20]`, generated by tools/gen_arlu_leaves.py from {sys.argv[1].split("/")[-1]} (sha256 {sha}). -/',
       '', 'set_option maxRecDepth 200000', 'set_option maxHeartbeats 0', '', 'namespace ArealUCore', '',
       'def leaves : List Leaf := [']
out.append(',\n'.join(f'  ⟨{t[1]}, {t[2]}, {t[3]}, {t[4]}, {"true" if t[5] else "false"}, {t[6]}⟩' for t in L))
out += [']', '', 'end ArealUCore', '']
open(sys.argv[2], 'w').write('\n'.join(out))
with open(sys.argv[3], 'w') as f:
    for t in L:
        if t[1] == 0: f.write(f'C {t[2]} {t[3]} {t[4]} {1 if t[5] else 0} {t[6]}\n')
        else: f.write(f'W {t[2]} {t[3]} {t[4]}\n')
print('leaves', len(L), 'start', L[0][2:5], 'end', (L[-1][3], L[-1][4]), 'sha', sha)
