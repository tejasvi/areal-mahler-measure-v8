#!/usr/bin/env python3
"""Generate ArealUCore/Data.lean (core Lean, no imports) from the frozen areal upper certificate U4b (read-only input).
The data are the certificate itself (polynomials, weights b_j, nodes, G values, v*, X) as exact integers.
usage: python3 -I gen_arlu_data.py CERT.json OUT_Data.lean"""
import json, sys, hashlib
from fractions import Fraction as Fr
cert_path, out = sys.argv[1], sys.argv[2]
raw = open(cert_path, 'rb').read(); sha = hashlib.sha256(raw).hexdigest()
c = json.loads(raw)
assert c['format'] == 'tpmahler-areal-upper-v1'
DEC = 10 ** 10
polys = c['polys']
bw = [Fr(x) for x in c['b']]
assert all(x > 0 and x.denominator & (x.denominator - 1) == 0 for x in bw)
nodes = [Fr(x) for x in c['nodes']]; assert all((x * DEC).denominator == 1 for x in nodes)
n = [int(x * DEC) for x in nodes]
assert all(a < b for a, b in zip(n, n[1:]))
G = [Fr(x) for x in c['G']]
assert all(x >= 0 and x.denominator & (x.denominator - 1) == 0 for x in G)
GS = max(x.denominator for x in G).bit_length() - 1
g = [int(x * (1 << GS)) for x in G]; assert all(Fr(gi, 1 << GS) == Gi for gi, Gi in zip(g, G))
v = Fr(c['v'])
X = Fr(c['X']); assert X == 20
assert polys[0] == [1, 0]
def lst(xs): return '[' + ', '.join(str(x) for x in xs) + ']'
L = []
L.append('/-! Data of the areal upper certificate (U4b), generated by tools/gen_arlu_data.py.')
L.append(f'Input SHA-256: {sha}. Core Lean only. -/')
L.append('')
L.append('set_option maxRecDepth 200000')
L.append('')
L.append('namespace ArealUCore')
L.append('')
L.append('/-- The polynomials `Q_j`, coefficients from the leading one down to the constant term. `Q_0 = x`. -/')
L.append('def polys : List (List Int) := ' + lst([lst(p) for p in polys]))
L.append('/-- The weights `b_j = cwNum_j / 2^cwSh_j`. -/')
L.append('def cwNum : List Nat := ' + lst([x.numerator for x in bw]))
L.append('def cwSh : List Nat := ' + lst([x.denominator.bit_length() - 1 for x in bw]))
L.append('/-- The nodes `e_i = nodes_i / 10^10`. -/')
L.append('def nodes : List Nat := ' + lst(n))
L.append(f'/-- `G_i = gvals_i / 2^GS`. -/')
L.append(f'def GS : Nat := {GS}')
L.append('def gvals : List Nat := ' + lst(g))
L.append('/-- `v* = vNum / vDen`. -/')
L.append(f'def vNum : Nat := {v.numerator}')
L.append(f'def vDen : Nat := {v.denominator}')
L.append('/-- `X = 20`: the interval `[0, X]` of Smith\'s theorem. -/')
L.append(f'def XX : Nat := {int(X)}')
L.append('')
L.append('end ArealUCore')
open(out, 'w').write('\n'.join(L) + '\n')
print('wrote', out, 'polys', len(polys), 'nodes', len(n), 'GS', GS, 'sha', sha)
