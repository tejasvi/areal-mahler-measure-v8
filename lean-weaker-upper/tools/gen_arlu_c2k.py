"""Emit the K modules of the areal upper certificate's global checks: (C2) split into kernel shards (one per root
bracket `uLoBracket`, one per Vieta pair for `zLogPart` and for `zAtanPart`), the per-polynomial assembly through
`ArealUK.C2Glue`, the collection `c2_facts_lit`, and the remaining global checks (budget, (V), irreducibility).
The piece values come from the native helper (`arluk c2parts`, data/c2parts_U4b.txt); the pair data from
ArealUCore/Roots.lean. Every value is re-checked by the kernel (`decide +kernel`).
usage: python3 -I gen_arlu_c2k.py c2parts.txt ArealUCore/Roots.lean OUTDIR"""
import re, sys

parts, roots, outdir = sys.argv[1], sys.argv[2], sys.argv[3]
HDR = """set_option maxRecDepth 200000
set_option maxHeartbeats 0

namespace ArealUCore.ArealUK
"""


def lit(x):
    return f'({x})' if x < 0 else str(x)


def parse_int(s):
    return int(s.strip('()'))


brs = {}     # j -> list of (X1, X2, k, u)
sl, zlog, zatan, c2 = {}, {}, {}, {}
for line in open(parts):
    t = line.split()
    if not t:
        continue
    if t[0] == 'br':
        brs.setdefault(int(t[1]), []).append((int(t[2]), int(t[3]), int(t[4]), parse_int(t[5])))
    elif t[0] == 'sl':
        sl[int(t[1])] = parse_int(t[2])
    elif t[0] == 'zlog':
        zlog[int(t[1])] = (parse_int(t[2]), parse_int(t[3]))
    elif t[0] == 'zatan':
        assert t[2] != 'none', line
        zatan[int(t[1])] = (parse_int(t[2]), parse_int(t[3]))
    elif t[0] == 'c2':
        m = re.match(r'c2 (\d+) \(some (\(?-?\d+\)?)\)', line.strip())
        assert m, line
        c2[int(m.group(1))] = parse_int(m.group(2))

# pair data, in order of the polynomials, from Roots.lean
rows = [l for l in open(roots) if l.strip().startswith('⟨[')]
pairs = {}
for j, l in enumerate(rows):
    m = re.search(r'some ⟨(\d+), (\d+), (\d+), (\d+), (\d+)⟩⟩', l)
    if m:
        pairs[j] = tuple(int(x) for x in m.groups())
    else:
        assert l.rstrip().rstrip(',').endswith('none⟩'), l[-80:]
J = len(rows)
assert sorted(c2) == list(range(J)) and sorted(sl) == list(range(J)), (J, sorted(c2))
assert sorted(zlog) == sorted(pairs) == sorted(zatan), (sorted(zlog), sorted(pairs))
for j in range(J):
    assert c2[j] > 0, (j, c2[j])

mods = []
gidx = 0
bnames = {}
for j in range(J):
    bnames[j] = []
    for (X1, X2, k, u) in brs.get(j, []):
        name = f'C2B{gidx:03d}'
        open(f'{outdir}/{name}.lean', 'w').write(f'''import ArealUCore.Lits
import ArealUCore.C2

/-! (C2) of the areal U4b (K): the lower bound `uLoBracket` of root bracket {gidx} (polynomial {j}).
Generated by tools/gen_arlu_c2k.py. -/

{HDR}
theorem br_{gidx:03d} : uLoBracket ctxLitU ⟨{X1}, {X2}, {k}⟩ = {lit(u)} := by
  decide +kernel

end ArealUCore.ArealUK
''')
        bnames[j].append((name, f'br_{gidx:03d}', X1, X2, k, u))
        mods.append(name)
        gidx += 1

for j, (Ua, Va, kz, du, dv) in pairs.items():
    lo, hi = zlog[j]
    s1, s2 = zatan[j]
    open(f'{outdir}/C2L{j:02d}.lean', 'w').write(f'''import ArealUCore.Lits
import ArealUCore.C2

/-! (C2) of the areal U4b (K): `zLogPart` at the point `z₀` of polynomial {j}. Generated by tools/gen_arlu_c2k.py. -/

{HDR}
theorem zlog_{j:02d} : zLogPart ctxLitU.tab ctxLitU.l2 ctxLitU.rs {Ua} {Va} {kz} (logT ctxLitU.tab ctxLitU.l2 (DEC * 2 ^ {kz}) 1) =
    ({lit(lo)}, {lit(hi)}) := by
  decide +kernel

end ArealUCore.ArealUK
''')
    open(f'{outdir}/C2A{j:02d}.lean', 'w').write(f'''import ArealUCore.Lits
import ArealUCore.C2

/-! (C2) of the areal U4b (K): `zAtanPart` at the point `z₀` of polynomial {j}. Generated by tools/gen_arlu_c2k.py. -/

{HDR}
theorem zatan_{j:02d} : zAtanPart ctxLitU.rs {Ua} {Va} {kz} = some ({lit(s1)}, {lit(s2)}) := by
  decide +kernel

end ArealUCore.ArealUK
''')
    mods += [f'C2L{j:02d}', f'C2A{j:02d}']

for j in range(J):
    bl = bnames[j]
    imports = ''.join(f'import ArealUK.{b[0]}\n' for b in bl)
    if j in pairs:
        imports += f'import ArealUK.C2L{j:02d}\nimport ArealUK.C2A{j:02d}\n'
    brlit = '[' + ', '.join(f'⟨{b[2]}, {b[3]}, {b[4]}⟩' for b in bl) + ']'
    ur = sum(b[5] for b in bl)
    rws = ''.join(f'foldl_uLo_cons {b[1]}, ' for b in bl)
    if j in pairs:
        Ua, Va, kz, du, dv = pairs[j]
        prlit = f'⟨{Ua}, {Va}, {kz}, {du}, {dv}⟩'
        rdlit = f'⟨{brlit}, some {prlit}⟩'
        main = f'''  rw [hrd, c2LB_eq_pair (c := ctxLitU) (desc := polys.getD {j} []) (pr := {prlit}) (sl := {lit(sl[j])})
    (by decide +kernel) hur (by decide +kernel) (by decide +kernel) zatan_{j:02d} zlog_{j:02d}]
  decide +kernel'''
    else:
        rdlit = f'⟨{brlit}, none⟩'
        main = f'''  rw [hrd, c2LB_eq_none (c := ctxLitU) (desc := polys.getD {j} []) (sl := {lit(sl[j])})
    (by decide +kernel) hur (by decide +kernel)]
  decide +kernel'''
    open(f'{outdir}/C2P{j:02d}.lean', 'w').write(f'''import ArealUK.C2Glue
import ArealUCore.Roots
{imports}
/-! (C2) of the areal U4b (K): polynomial {j}, assembled from its kernel-checked pieces (`ArealUK.C2Glue`).
Generated by tools/gen_arlu_c2k.py. -/

{HDR}
theorem c2_{j:02d} : c2LB ctxLitU (polys.getD {j} []) (rootData.getD {j} ⟨[], none⟩) = some {lit(c2[j])} ∧
    (0 : Int) < {lit(c2[j])} := by
  have hrd : rootData.getD {j} ⟨[], none⟩ = {rdlit} := by decide +kernel
  have hur : List.foldl (fun a b => a + uLoBracket ctxLitU b) 0 {brlit} = {lit(ur)} := by
    rw [{rws}List.foldl_nil]
    decide +kernel
{main}

end ArealUCore.ArealUK
''')
    mods.append(f'C2P{j:02d}')

cases = ''.join(f'  | {j}, _ => ⟨_, c2_{j:02d}⟩\n' for j in range(J))
open(f'{outdir}/C2All.lean', 'w').write(''.join(f'import ArealUK.C2P{j:02d}\n' for j in range(J)) + f'''
/-! (C2) of the areal U4b (K), all {J} polynomials. Generated by tools/gen_arlu_c2k.py. -/

{HDR}
theorem c2_facts_lit : ∀ j : Nat, j < {J} →
    ∃ v, c2LB ctxLitU (polys.getD j []) (rootData.getD j ⟨[], none⟩) = some v ∧ 0 < v
{cases}  | _ + {J}, h => absurd h (by omega)

end ArealUCore.ArealUK
''')
mods.append('C2All')

for name, stmt, doc in [
        ('GBudget', 'theorem budget_ok : budgetOK = true := by\n  decide +kernel', '(C1) budget'),
        ('GIrred', 'theorem irred_ok : irredAll polys rootData = true := by\n  decide +kernel', 'irreducibility'),
        ('GV', 'theorem v_ok_lit : vOK ctxLitU = true := by\n  decide +kernel', '(V)')]:
    open(f'{outdir}/{name}.lean', 'w').write(f'''import ArealUCore.Lits
import ArealUCore.Roots
import ArealUCore.V
import ArealUCore.Irred

/-! Global check of the areal U4b (K): {doc}. Generated by tools/gen_arlu_c2k.py. -/

{HDR}
{stmt}

end ArealUCore.ArealUK
''')
    mods.append(name)

open(f'{outdir}/c2k_modules.txt', 'w').write('\n'.join(mods) + '\n')
print(len(mods), 'modules;', gidx, 'brackets;', len(pairs), 'pairs')
