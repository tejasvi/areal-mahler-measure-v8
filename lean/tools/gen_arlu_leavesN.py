#!/usr/bin/env python3
"""Emit Areal/UCert/LeavesN.lean (the N tiling shards ArealUN.chunk_NNN composed into leavesOK_full_N) from ArealUN/chunks.json.
usage: python3 -I gen_arlu_leavesN.py CHUNKS.json OUT.lean NPOLYS INTERVAL_TEXT   (e.g. 23 '[237/1600, 20]')"""
import json, sys
rows = json.load(open(sys.argv[1])); out, npolys, ivtext = sys.argv[2], int(sys.argv[3]), sys.argv[4]
n = len(rows)
X0, k0 = rows[0][3], rows[0][4]; XT, kT = rows[-1][5], rows[-1][6]
o = [f'import ArealUN.{r[0]}' for r in rows]
o += ['import Areal.UCert.LeavesCommon', '',
      '/-! The complete (C3) tiling check of the upper certificate (N): the shards `ArealUN.chunk_NNN` composed.',
      'Generated by tools/gen_arlu_leavesN.py (inline). -/', '', 'open Set', '', 'namespace Areal.UCert', '',
      'open ArealUCore AuxCore AuxCommon', '']
o.append(f'theorem leavesOK_full_N : leavesOK ctxU {X0} {k0} leaves {XT} {kT} = true := by')
last = rows[-1]
o.append(f'  have s{n - 1} : leavesOK ctxU {last[3]} {last[4]} (leaves.drop {last[1]}) {XT} {kT} = true := by')
o.append(f'    have h := ArealUCore.ArealUN.chunk_{n - 1:03d}')
o.append('    rwa [List.take_of_length_le (by rw [List.length_drop, leaves_length])] at h')
for i in range(n - 2, -1, -1):
    r = rows[i]
    o.append(f'  have s{i} : leavesOK ctxU {r[3]} {r[4]} (leaves.drop {r[1]}) {XT} {kT} = true :=')
    o.append(f'    chunk_step (a := {r[1]}) (n := {r[2]}) ArealUCore.ArealUN.chunk_{i:03d} s{i + 1}')
o.append('  simpa using s0')
o.append('')
o.append('theorem winBelow_all_N : leaves.all winBelow = true := by native_decide')
o.append('')
o.append('theorem leaves_ne_nil : leaves ≠ [] := by\n  intro h\n  have := leaves_length\n  rw [h] at this\n  simp at this')
o.append('')
o.append(f'/-- `F > 0` on `{ivtext}` off the roots (N). -/')
o.append(f'theorem FR_pos_N : ∀ x ∈ Icc (({X0} : ℕ) / (DEC * 2 ^ {k0} : ℕ) : ℝ) (({XT} : ℕ) / (DEC * 2 ^ {kT} : ℕ) : ℝ),')
o.append(f'      (∀ j < {npolys}, (QR (polys.getD j [])).eval x ≠ 0) → 0 < FR x :=')
o.append('  leavesOK_sound_Icc leaves _ _ _ _ leaves_ne_nil (winBelow_real_of winBelow_all_N) leavesOK_full_N')
o.append('')
o.append('end Areal.UCert')
open(out, 'w').write('\n'.join(o) + '\n')
print('wrote', out, n, 'shards')
