#!/usr/bin/env python3
"""Root data for check (C2) of the areal upper certificate: for each polynomial, brackets [X1, X2]/(10^10 2^K) of
its real roots (exact bisection on integer polynomial values: X2 - X1 = 1, or X1 = X2 at an exact root), and for the
polynomials with one non-real pair the point z0 = (Ua + i Va)/(10^10 2^KZ) and dn with Vieta's check done exactly here.
Writes ArealUCore/Roots.lean. Approximate roots from numpy (sci venv) seed the bisection.
usage: python gen_arlu_roots.py CERT.json"""
import json, sys, os
from fractions import Fraction as Fr
import numpy as np
H = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
c = json.load(open(sys.argv[1]))
polys = c['polys']
DEC = 10 ** 10
K = 120
D = DEC << K
KZ = 120
DZ = DEC << KZ
DU = 1 << 16
DV = 1 << 28
def ev(desc, X, Dd):
    # D^d Q(X/D) exactly
    v = 0
    for a in desc:
        v = v * X + a * 1
        # Horner on Q(X/D)*D^d: accumulate with powers of D
    d = len(desc) - 1
    v = 0
    for i, a in enumerate(desc):
        v += a * X ** (d - i) * Dd ** i
    return v
def isqrt(n):
    import math
    return math.isqrt(n)
out = []
stats = []
for j, desc in enumerate(polys):
    d = len(desc) - 1
    r = np.roots(desc)
    reals = sorted(float(z.real) for z in r if abs(z.imag) < 1e-7)
    nonreal = [z for z in r if abs(z.imag) >= 1e-7]
    brs = []
    for x in reals:
        # initial bracket from the float root
        lo = int((Fr(x) - Fr(1, 10 ** 9)) * D) if x > 1e-9 else 0
        hi = int((Fr(x) + Fr(1, 10 ** 9)) * D) + 1
        flo, fhi = ev(desc, lo, D), ev(desc, hi, D)
        if x <= 1e-9 and flo == 0:
            brs.append((0, 0)); continue
        assert flo * fhi < 0, (j, x, flo, fhi)
        exact = None
        while hi - lo > 1:
            m = (lo + hi) // 2
            fm = ev(desc, m, D)
            if fm == 0:
                exact = m; break
            if (fm < 0) == (flo < 0):
                lo, flo = m, fm
            else:
                hi, fhi = m, fm
        brs.append((exact, exact) if exact is not None else (lo, hi))
    for a, b in zip(brs, brs[1:]):
        assert a[1] < b[0]
    pair = None
    if nonreal:
        assert len(nonreal) == 2 and len(brs) == d - 2, (j, len(nonreal), len(brs))
        an, an1, a0 = desc[0], desc[1], desc[-1]
        p0 = a0 if d % 2 == 0 else -a0
        s1 = sum(b[0] for b in brs); s2 = sum(b[1] for b in brs)
        p1 = 1; p2 = 1
        for b in brs:
            p1 *= b[0]; p2 *= b[1]
        m = len(brs)
        sig_lo = Fr(-an1, an) - Fr(s2, D); sig_hi = Fr(-an1, an) - Fr(s1, D)
        pi_lo = Fr(p0 * D ** m, an * p2); pi_hi = Fr(p0 * D ** m, an * p1)
        u = (sig_lo + sig_hi) / 4
        v2 = (pi_lo + pi_hi) / 2 - u * u
        Ua = round(u * DZ)
        Va = isqrt(int(v2 * DZ * DZ))
        # Vieta check exactly as pairOK
        dz = DZ; dc = D; du = DU; dv = DV; ua = Ua; va = Va; uabs = abs(ua)
        conds = [0 < an, 0 < p0, 0 < p1, dv < va, du <= uabs,
              2 * (ua - du) * an * dc <= (-an1 * dc - an * s2) * dz,
              (-an1 * dc - an * s1) * dz <= 2 * (ua + du) * an * dc,
              ((va - dv) ** 2 + (uabs + du) ** 2) * an * p2 <= p0 * dc ** m * dz ** 2,
              p0 * dc ** m * dz ** 2 <= ((va + dv) ** 2 + (uabs - du) ** 2) * an * p1]
        assert all(conds), (j, conds)
        pair = (Ua, Va, KZ, DU, DV)
        zf = complex(nonreal[0].real, abs(nonreal[0].imag))
        stats.append((j, float(Fr(Ua, DZ)), float(Fr(Va, DZ)), zf))
    out.append((brs, pair))
L = ['import ArealUCore.C2', '', '/-! Root data for (C2) of the areal upper certificate (hints; every claim is checked by `c2LB`).',
     'Generated by tools/gen_arlu_roots.py. -/', '', 'set_option maxRecDepth 200000', '', 'namespace ArealUCore', '',
     'def rootData : List RootData := [']
items = []
for brs, pair in out:
    bl = ', '.join(f'⟨{a}, {b}, {K}⟩' for a, b in brs)
    pr = 'none' if pair is None else f'some ⟨{pair[0] if pair[0] >= 0 else "(" + str(pair[0]) + ")"}, {pair[1]}, {pair[2]}, {pair[3]}, {pair[4]}⟩'
    items.append(f'  ⟨[{bl}], {pr}⟩')
L.append(',\n'.join(items) + ']')
L += ['', 'end ArealUCore', '']
open(f'{H}/ArealUCore/Roots.lean', 'w').write('\n'.join(L))
json.dump([dict(j=j, X0=a, X1=b, K=K) for j, (brs, _) in enumerate(out) for a, b in brs], open(f'{H}/data/roots_U5b.json', 'w'))
print('polys', len(out), 'brackets', sum(len(b) for b, _ in out), 'pairs', sum(1 for _, p in out if p))
for s in stats: print('pair', s)
